// Переменные для отслеживания времени выполнения программы
auto время_начала_решения = std::chrono::high_resolution_clock::now();

// Сигнатура для определения источника входных данных
char *знак_источника_данных = "";

// Атомарная переменная для сигнализации о завершении процесса
std::atomic<int> terminated;

// Результат решения (10 - выполнима, 20 - невыполнима, 0 - неизвестно)
int result = 0;

// Количество конфликтов в процессе решения при победы
int статистика_конфликтов_победителя;

// Модель (присваивание значений переменным) для выполнимой формулы
vec<int> model;

// Рабочая функция для парсинга входных данных в отдельном потоке
// arg - указатель на объект basesolver (решатель)
void *функция_чтения_данных(void *arg)
{
    basesolver *решатель = (basesolver *)arg;
    
    // Если источник данных не установлен, читаем из препроцессора
    // Иначе читаем из CNF файла по установленному пути
    if (знак_источника_данных == "")
        решатель->parse_from_PAR(решатель->controller->pre);
    else
        решатель->parse_from_CNF(знак_источника_данных);
    
    return NULL;
}

// Основная рабочая функция решателя для отдельного потока
// arg - указатель на объект basesolver (решатель)
void *функция_решения_sat(void *arg)
{
    basesolver *решатель = (basesolver *)arg;
    
    // Основной цикл решения - продолжаем, пока не получен результат или не произведено завершение
    while (!terminated)
    {
        // Выполняем один цикл решения с динамической доработкой стратегии
        int результат = решатель->solve();
        
        // Если режим с динамическим управлением конфликтами (DCE) включен
        if (решатель->controller->opt->DCE)
        {
            if (результат)
            {
                terminated = 1;
                result = результат;
                решатель->internal_terminate();
                решатель->controller->update_winner(решатель->id, решатель->period);
                
                // Если формула выполнима, получаем модель
                if (результат == 10)
                    решатель->get_model(решатель->model);
            }
        }
        else
        {
            // Стандартный режим решения без DCE
            if (результат && !terminated)
            {
                terminated = 1;
                решатель->controller->terminate_workers();
                result = результат;
                решатель->controller->update_winner(решатель->id, 0);
                статистика_конфликтов_победителя = решатель->get_conflicts();
                
                // Если формула выполнима, получаем модель
                if (результат == 10)
                    решатель->get_model(решатель->model);
            }
        }
    }
    
    return NULL;
}

// Инициализация всех рабочих потоков
// Создает требуемое количество решателей на основе параметра nThreads
void light::init_workers()
{
    // Сброс флага завершения
    terminated = 0;
    
    // Создание и добавление каждого решателя в вектор рабочих
    for (int индекс_потока = 0; индекс_потока < OPT(nThreads); индекс_потока++)
    {
        basekissat *новый_решатель = new basekissat(индекс_потока, this);
        workers.push(новый_решатель);
    }
}

// Установка разнообразной конфигурации для каждого рабочего потока
// Применяет различные стратегии решения для повышения эффективности параллельного решения
void light::diversity_workers()
{
    // Для каждого рабочего потока применяем уникальную конфигурацию
    for (int индекс = 0; индекс < OPT(nThreads); индекс++)
    {
        // Если включена перемешивание порядка переменных (shuffle)
        if (OPT(shuffle))
        {
            if (индекс)
                workers[индекс]->configure("order_reset", индекс);
        }
        
        // Если включена конфигурация PAKIS (параллельно-адаптивная система)
        if (OPT(pakis))
        {
            // Настройка уровня обучения (tier1) - определяет активность хевристик
            if (индекс == 13 || индекс == 14 || индекс == 20 || индекс == 21)
                workers[индекс]->configure("tier1", 3);
            else
                workers[индекс]->configure("tier1", 2);

            // Настройка хронологического обратного отслеживания (chrono)
            if (индекс == 3 || индекс == 4 || индекс == 6 || индекс == 8 || 
                индекс == 11 || индекс == 12 || индекс == 13 || индекс == 14 || 
                индекс == 16 || индекс == 18 || индекс == 23)
                workers[индекс]->configure("chrono", 0);
            else
                workers[индекс]->configure("chrono", 1);

            // Настройка стабилизации переменных (stable)
            if (индекс == 2 || индекс == 23)
                workers[индекс]->configure("stable", 0);
            else if (индекс == 6 || индекс == 16)
                workers[индекс]->configure("stable", 2);
            else
                workers[индекс]->configure("stable", 1);

            // Настройка инициального случайного хода (walkinitially)
            if (индекс == 10 || индекс == 22)
                workers[индекс]->configure("walkinitially", 1);
            else
                workers[индекс]->configure("walkinitially", 0);

            // Настройка целевого режима поиска (target)
            if (индекс == 7 || индекс == 8 || индекс == 9 || 
                индекс == 17 || индекс == 18 || индекс == 19 || индекс == 20)
                workers[индекс]->configure("target", 0);
            else if (индекс == 0 || индекс == 2 || индекс == 3 || индекс == 4 || 
                     индекс == 5 || индекс == 6 || индекс == 10 || индекс == 23)
                workers[индекс]->configure("target", 1);
            else
                workers[индекс]->configure("target", 2);

            // Настройка инициализации фазы (phase)
            if (индекс == 4 || индекс == 5 || индекс == 8 || индекс == 9 || 
                индекс == 12 || индекс == 13 || индекс == 15 || индекс == 18 || индекс == 19)
                workers[индекс]->configure("phase", 0);
            else
                workers[индекс]->configure("phase", 1);
        }
    }
}

// Корректное завершение работы всех рабочих потоков
void light::terminate_workers()
{
    // Завершение всех решателей в соответствии с установками конфигурации
    for (int индекс = 0; индекс < OPT(nThreads); индекс++)
    {
        // Если включена глобальная обработка конфликтов и динамическое управление
        if (OPT(clause_sharing) == 1 && OPT(DCE) == 1)
            workers[индекс]->external_terminate();
        else
            workers[индекс]->terminate();
    }
    
    // Уведомление всех обменивателей информацией о завершении
    for (int индекс = 0; индекс < sharers.size(); индекс++)
    {
        sharers[индекс]->set_terminated();
    }
}

// Парсинг входного CNF файла во вспомогательных потоках
void light::parse_input()
{
    // Создание массива дескрипторов потоков
    pthread_t *массив_потоков = new pthread_t[OPT(nThreads)];
    
    // Запуск рабочей функции чтения в каждом потоке
    for (int индекс = 0; индекс < OPT(nThreads); индекс++)
    {
        pthread_create(&массив_потоков[индекс], NULL, функция_чтения_данных, workers[индекс]);
    }
    
    // Ожидание завершения всех потоков чтения
    for (int индекс = 0; индекс < OPT(nThreads); индекс++)
    {
        pthread_join(массив_потоков[индекс], NULL);
    }
    
    // Освобождение памяти под дескрипторы потоков
    delete[] массив_потоков;
}

// Основная функция решения SAT задачи с многопоточностью
// Запускает рабочие потоки и контролирует время выполнения
int light::solve()
{
    // Создание массива для хранения дескрипторов рабочих потоков
    pthread_t *массив_потоков_решения = new pthread_t[OPT(nThreads)];
    
    // Создание и запуск рабочего потока для каждого решателя
    for (int индекс = 0; индекс < OPT(nThreads); индекс++)
    {
        pthread_create(&массив_потоков_решения[индекс], NULL, функция_решения_sat, workers[индекс]);
    }

    // Основной цикл контроля времени - продолжаем, пока не получен результат
    while (!terminated)
    {
        // Небольшая задержка для экономии процессорных ресурсов (100ms)
        usleep(100000);
        
        // Получение текущего времени
        auto текущее_время = std::chrono::high_resolution_clock::now();
        
        // Вычисление прошедшего времени в секундах с начала выполнения
        int прошедшее_время_сек = std::chrono::duration_cast<std::chrono::seconds>(
            текущее_время - время_начала_решения
        ).count();
        
        // Если превышено максимальное время, принудительно завершаем все потоки
        if (прошедшее_время_сек >= OPT(cutoff))
        {
            terminated = 1;
            terminate_workers();
        }
    }

    // Ожидание завершения всех рабочих потоков
    for (int индекс = 0; индекс < OPT(nThreads); индекс++)
    {
        pthread_join(массив_потоков_решения[индекс], NULL);
    }

    // Если найдена выполнимая модель, копируем её из потока-победителя
    if (result == 10)
        workers[winner_id]->model.copyTo(model);
    
    // Освобождение памяти под дескрипторы потоков
    delete[] массив_потоков_решения;
    
    return result;
}

// Главный процесс: инициализация, парсинг, решение и постобработка результата
int light::run()
{
    // Инициализация всех рабочих потоков
    init_workers();
    
    // Применение разнообразной конфигурации для каждого потока
    diversity_workers();
    
    // Если включен препроцессор, выполняем его для упрощения формулы
    if (OPT(preprocessor))
    {
        pre = new preprocess();
        int результат_препроцессинга = pre->do_preprocess(filename);
        
        // Если формула невыполнима на этапе препроцессинга
        if (результат_препроцессинга == 20)
            return 20;
        // Если формула выполнима сразу (тривиальный случай)
        else if (результат_препроцессинга == 10)
        {
            for (int переменная = 1; переменная <= pre->vars; переменная++)
            {
                model.push(pre->model[переменная]);
            }
            return 10;
        }
    }
    else
        // Если препроцессор отключен, используем входной файл напрямую
        знак_источника_данных = filename;
    
    // Парсинг входных данных во всех потоках
    parse_input();
    
    // Если включен обмен информацией между потоками, инициируем его
    if (OPT(clause_sharing))
        share();
    
    // Запуск основного процесса решения
    int результат_решения = solve();
    
    // Постобработка результата: восстановление полной модели с учетом препроцессинга
    if (результат_решения == 10 && OPT(preprocessor))
    {
        // Восстановление значений переменных, которые были исключены препроцессором
        for (int оригинальная_переменная = 1; оригинальная_переменная <= pre->orivars; оригинальная_переменная++)
            if (pre->mapto[оригинальная_переменная])
                pre->mapval[оригинальная_переменная] = 
                    (model[abs(pre->mapto[оригинальная_переменная]) - 1] > 0 ? 1 : -1) * 
                    (pre->mapto[оригинальная_переменная] > 0 ? 1 : -1);
        
        // Получение полной модели с восстановленными переменными
        pre->get_complete_model();
        
        // Очистка и переформирование модели в требуемый формат
        model.clear();
        for (int переменная = 1; переменная <= pre->orivars; переменная++)
        {
            model.push(переменная * pre->mapval[переменная]);
        }
    }
    
    return результат_решения;
}

// Функция вывода полученной модели в требуемом формате CNF
// model - вектор присваиваний значений переменным
void вывести_модель(vec<int> &model)
{
    printf("v");
    for (int индекс = 0; индекс < model.size(); индекс++)
    {
        printf(" %d", model[индекс]);
    }
    puts(" 0");
}

// Главная функция программы, вызывается из main
// Инициирует процесс решения и выводит результат в стандартный формат DIMACS
void solve(int argc, char **argv)
{
    // Создание объекта главного контроллера
    light *контроллер_решателя = new light();
    
    // Парсинг аргументов командной строки
    контроллер_решателя->arg_parse(argc, argv);
    
    // Запуск основного процесса решения
    int финальный_результат = контроллер_решателя->run();
    
    // Вывод результата в требуемом формате
    if (финальный_результат == 10)
    {
        printf("s SATISFIABLE\n");
        вывести_модель(model);
    }
    else if (финальный_результат == 20)
    {
        printf("s UNSATISFIABLE\n");
    }
    else
    {
        printf("s UNKNOWN\n");
    }
    
    // Освобождение памяти
    delete (контроллер_решателя);
    return;
}